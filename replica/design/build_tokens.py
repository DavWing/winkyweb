#!/usr/bin/env python3
"""Generate tokens.css (plain CSS custom properties) and tailwind.css
(Tailwind v4 theme mapping) from tokens.json. Standard library only.

    python3 replica/design/build_tokens.py

Run after every token change, including /replica-brand. Never edit the
generated files by hand.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
tokens = json.load(open(os.path.join(HERE, "tokens.json")))

# role name in tokens.json -> Tailwind colour name, so components read
# bg-surface, text-fg, text-secondary, text-muted, border-input, ...
TW_COLOR = {"text": "fg", "text-secondary": "secondary", "text-muted": "muted"}

HEADER = "/* Generated by build_tokens.py from tokens.json. Do not edit. */\n"

css = [HEADER, ":root {"]
for name, value in tokens["color"].items():
    css.append(f"  --tk-{name}: {value};")
for name, value in tokens["font"].items():
    css.append(f"  --tk-font-{name}: {value};")
for name, t in tokens["type"].items():
    css.append(f"  --tk-text-{name}: {t['size']}px;")
    css.append(f"  --tk-text-{name}-line: {t['line']}px;")
    css.append(f"  --tk-text-{name}-weight: {t['weight']};")
for name, value in tokens["radius"].items():
    css.append(f"  --tk-radius-{name}: {value}px;")
for name, value in tokens["shadow"].items():
    css.append(f"  --tk-shadow-{name}: {value};")
for name, value in tokens["motion"].items():
    css.append(f"  --tk-motion-{name}: {value};")
for name, value in tokens["layout"].items():
    if isinstance(value, dict):
        continue
    css.append(f"  --tk-{name}: {value if isinstance(value, str) else str(value) + 'px'};")
css.append("}")
open(os.path.join(HERE, "tokens.css"), "w").write("\n".join(css) + "\n")

tw = [HEADER, '@import "tailwindcss";', '@import "./tokens.css";', "",
      "@theme inline {",
      "  /* tokens only: drop Tailwind's default palette so raw colours can't creep in */",
      "  --color-*: initial;",
      "  --color-white: #ffffff;",
      "  --color-transparent: transparent;",
      "  --color-current: currentColor;"]
for name in tokens["color"]:
    tw.append(f"  --color-{TW_COLOR.get(name, name)}: var(--tk-{name});")
tw.append(f"  --font-sans: var(--tk-font-sans);")
tw.append(f"  --font-mono: var(--tk-font-mono);")
for name in tokens["type"]:
    tw.append(f"  --text-{name}: var(--tk-text-{name});")
    tw.append(f"  --text-{name}--line-height: var(--tk-text-{name}-line);")
    tw.append(f"  --text-{name}--font-weight: var(--tk-text-{name}-weight);")
tw.append("  --radius-*: initial;")
for name in tokens["radius"]:
    tw.append(f"  --radius-{name}: var(--tk-radius-{name});")
tw.append("  --shadow-*: initial;")
for name in tokens["shadow"]:
    tw.append(f"  --shadow-{name}: var(--tk-shadow-{name});")
tw.append("  --spacing: 4px;")
for name, px in tokens["layout"]["breakpoints"].items():
    tw.append(f"  --breakpoint-{name}: {px}px;")
tw.append("}")
open(os.path.join(HERE, "tailwind.css"), "w").write("\n".join(tw) + "\n")
print("wrote tokens.css and tailwind.css")
